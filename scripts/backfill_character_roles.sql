-- anime_rank をロール基準で再計算（MAIN→SUPPORTING→BACKGROUND、同一ロール内はfavourites順）
UPDATE characters c SET anime_rank = sub.rank
FROM (
    SELECT character_id,
           ROW_NUMBER() OVER (
               PARTITION BY anime_id
               ORDER BY
                   CASE role
                       WHEN 'MAIN'       THEN 1
                       WHEN 'SUPPORTING' THEN 2
                       ELSE                   3
                   END,
                   favourites DESC NULLS LAST
           ) AS rank
    FROM characters
) sub
WHERE c.character_id = sub.character_id;